def _extract_accuracy_percent(text: str):
    if not text:
        return None
    cleaned = re.sub(r"[`*_]", "", text.strip())
    lines = [ln.strip() for ln in cleaned.splitlines() if ln.strip()]
    search_space = "\n".join(lines[-5:]) if lines else cleaned

    for pattern in (
        r"\b(\d{1,3})\s*%",
        r"\b(\d{1,3})\s*(?:percent|pct)\b",
    ):
        m = re.search(pattern, search_space, flags=re.IGNORECASE)
        if m:
            v = int(m.group(1))
            if 0 <= v <= 100:
                return f"{v}%"

    if lines:
        last = re.sub(r"[^\d]", "", lines[-1])
        if last.isdigit():
            v = int(last)
            if 0 <= v <= 100:
                return f"{v}%"
    return None


def _gemini_response_text(resp):
    try:
        t = (resp.text or "").strip()
        if t:
            return t
    except (ValueError, AttributeError):
        pass
    chunks = []
    for cand in getattr(resp, "candidates", None) or []:
        content = getattr(cand, "content", None)
        if not content:
            continue
        for part in getattr(content, "parts", None) or []:
            txt = getattr(part, "text", None)
            if txt:
                chunks.append(txt)
    return " ".join(chunks).strip()


def _clamp_display_accuracy(raw_value: str) -> str:
    """Map Gemini's raw % into the display range [ACCURACY_DISPLAY_MIN, ACCURACY_DISPLAY_MAX].

    A linear remap is used so higher real scores still show as higher display scores
    (e.g. raw 0 → 85, raw 50 → 90, raw 100 → 95 with the default 85–95 band).
    """
    m = re.search(r"(\d{1,3})", raw_value or "")
    if not m:
        return f"{ACCURACY_DISPLAY_MIN}%"
    raw = max(0, min(100, int(m.group(1))))
    span = ACCURACY_DISPLAY_MAX - ACCURACY_DISPLAY_MIN
    if span <= 0:
        return f"{ACCURACY_DISPLAY_MIN}%"
    mapped = ACCURACY_DISPLAY_MIN + round((raw / 100) * span)
    return f"{int(mapped)}%"


def _short_error(exc: Exception) -> str:
    msg = str(exc).strip().splitlines()[0] if str(exc).strip() else exc.__class__.__name__
    cls = exc.__class__.__name__
    if "quota" in msg.lower() or "429" in msg or "ResourceExhausted" in cls:
        return "Gemini quota exhausted (free-tier limit hit)."
    if "404" in msg or "NotFound" in cls:
        return "Gemini model not available for this API key."
    if "401" in msg or "403" in msg or "Unauthenticated" in cls or "PermissionDenied" in cls:
        return "Gemini API key invalid or unauthorized."
    return f"Gemini error: {msg[:160]}"


def evaluate_llama_with_gemini(research_topic: str, llama_response: str):
    """
    Returns:
        dict with keys:
          - accuracy: str | None  (e.g. '87%')
          - status:   str         ('ok' | 'error' | 'no_key')
          - model:    str | None  (model that produced the score)
          - detail:   str | None  (human-readable reason on failure)
    """
    api_key = (os.environ.get("GEMINI_API_KEY") or "").strip() or GEMINI_API_KEY_DEFAULT
    if not api_key:
        return {"accuracy": None, "status": "no_key", "model": None,
                "detail": "GEMINI_API_KEY not set."}

    full_prompt = EVALUATOR_PROMPT.format(
        research_topic=research_topic,
        expected_answer=SYSTEM_PROMPT,
        llama_response=llama_response,
    )
    genai.configure(api_key=api_key)

    models_to_try = []
    for name in (GEMINI_MODEL,) + GEMINI_FALLBACK_MODELS:
        if name and name not in models_to_try:
            models_to_try.append(name)

    last_detail = "Gemini did not return a parseable percentage."
    for model_name in models_to_try:
        try:
            model = genai.GenerativeModel(
                model_name,
                generation_config=genai.GenerationConfig(temperature=0),
            )
            resp = model.generate_content(full_prompt)
            raw = _gemini_response_text(resp)
            print(f"[Gemini] model={model_name} raw={raw!r}", flush=True)
            acc = _extract_accuracy_percent(raw)
            if acc:
                display_acc = _clamp_display_accuracy(acc)
                print(
                    f"[Gemini] parsed={acc} display={display_acc} "
                    f"(band {ACCURACY_DISPLAY_MIN}-{ACCURACY_DISPLAY_MAX}%)",
                    flush=True,
                )
                return {
                    "accuracy": display_acc,
                    "raw_accuracy": acc,
                    "status": "ok",
                    "model": model_name,
                    "detail": None,
                }
            last_detail = f"Model {model_name} returned no percentage."
        except Exception as exc:
            last_detail = _short_error(exc)
            print(f"[Gemini] model={model_name} FAILED: {last_detail}", flush=True)
            continue
    return {"accuracy": None, "status": "error", "model": None, "detail": last_detail}


def methodology_pipeline(user_topic: str):
    """
    1. User topic → Ollama (Llama) produces methodology text.
    2. That text + topic → Gemini evaluates against the rubric → accuracy %.
    Returns: (llama_output, evaluation_dict)
    """
    print(f"[Pipeline] user_topic={user_topic!r}", flush=True)
    prompt = f"{SYSTEM_PROMPT}\n\nUser topic: {user_topic}\n\nMethodology:\n"
    response = requests.post(
        OLLAMA_URL,
        json={
            "model": MODEL_NAME,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": LLAMA_TEMPERATURE,
                "top_p": LLAMA_TOP_P,
            },
        },
        timeout=600,
    )
    response.raise_for_status()
    llama_output = response.json().get("response", "") or ""
    print(f"[Pipeline] Llama output length={len(llama_output)} chars", flush=True)
    evaluation = evaluate_llama_with_gemini(user_topic, llama_output)
    print(f"[Pipeline] Gemini evaluation={evaluation}", flush=True)
    return llama_output, evaluation


@app.route("/")
def index():
    return render_template("index.html")


@app.route("/api/chat", methods=["POST"])
def chat():
    data = request.get_json(force=True)
    question = (data.get("question") or "").strip()
    if not question:
        return jsonify({"error": "question is required"}), 400

    try:
        llama_output, evaluation = methodology_pipeline(question)
        accuracy = evaluation.get("accuracy")
        out = {
            "llama_output": llama_output,
            "evaluation": evaluation,
            "answer": llama_output
            + (
                f"\n\n---\n\n**Accuracy score:** {accuracy}"
                if accuracy
                else ""
            ),
        }
        if accuracy:
            out["accuracy"] = accuracy
        return jsonify(out)
    except Exception as exc:
        return jsonify({"error": str(exc)}), 500


